import { expect, test } from '@playwright/test'
import { closeBrowsers, expectVideoFlowing, instrumentDisplayCapture, instrumentPeerConnections, person, type Person } from './support'

test.afterEach(closeBrowsers)
const password = 'senha-segura-comunidades-2026'
async function register(p: Person, name: string) {
  await p.page.goto('/register')
  await p.page.getByLabel('Nome de usuário').fill(name)
  await p.page.getByLabel('Senha', { exact: true }).fill(password)
  await p.page.getByLabel('Confirmar senha').fill(password)
  await p.page.getByRole('button', { name: 'Criar conta', exact: true }).click()
  await expect(p.page.locator('.user-panel')).toContainText(name)
}
async function share(p: Person, resolution = '720p', fps = '30') {
  await p.page.getByRole('button', { name: /Compartilhar tela/ }).click()
  const modal = p.page.getByRole('dialog')
  await modal.getByLabel('Resolução').selectOption(resolution)
  await modal.getByLabel('FPS', { exact: true }).selectOption(fps)
  await modal.getByRole('button', { name: 'Começar transmissão' }).click()
  await expect(p.page.getByRole('button', { name: /Parar transmissão/, exact: false }).last()).toBeVisible()
}

test('servidor, convite, presença, três telas, foco, ocultar, qualidade ao vivo e saída', async ({ baseURL }) => {
  test.setTimeout(180000)
  const suffix = Date.now()
  const a = await person('A', 'chromium', baseURL!)
  const b = await person('B', 'chromium', baseURL!)
  const c = await person('C', 'chromium', baseURL!)
  const d = await person('D', 'chromium', baseURL!)
  for (const p of [a, b, c, d]) p.page.setDefaultTimeout(15000)
  for (const p of [a, b, c, d]) { await instrumentPeerConnections(p); await instrumentDisplayCapture(p); p.page.on('console', (m) => { if (m.type() === 'error') console.log(`${p.name}: ${m.text()}`) }) }
  const names = [a, b, c, d].map((p) => `${p.name}_${suffix}`)
  await register(a, names[0]!)
  await a.page.getByRole('button', { name: 'Adicionar servidor', exact: true }).first().click()
  await a.page.getByLabel('Nome do servidor', { exact: true }).fill('Amigos')
  await a.page.getByRole('button', { name: 'Criar servidor', exact: true }).click()
  await expect(a.page.getByRole('button', { name: 'Criar canal' })).toBeVisible()
  await a.page.getByRole('button', { name: 'Criar canal' }).click()
  await a.page.getByLabel('Nome do canal').fill('Jogos')
  await a.page.getByRole('button', { name: 'Salvar canal' }).click()
  await a.page.getByRole('button', { name: /Convidar amigos/ }).click()
  await a.page.getByRole('button', { name: 'Gerar convite' }).click()
  const invite = await a.page.getByLabel('Link de convite').inputValue()
  await a.page.getByRole('button', { name: 'Fechar', exact: true }).click()
  const serverUrl = a.page.url()
  for (const [index, p] of [b, c, d].entries()) {
    await register(p, names[index + 1]!)
    await p.page.goto(invite)
    await p.page.getByRole('button', { name: 'Entrar no servidor' }).click()
    await expect(p.page.getByRole('button', { name: /#\s*Jogos/ })).toBeVisible()
  }
  for (const p of [a, b, c, d]) {
    await p.page.getByRole('button', { name: /#\s*Jogos/ }).click()
    await expect(p.page.getByRole('button', { name: /Compartilhar tela/ })).toBeEnabled()
  }
  await expect(d.page.locator('.compact-participant')).toHaveCount(4)
  await share(a, '1080p', '60'); await share(b, '720p', '60'); await share(c)
  await expect(d.page.locator('.stream-grid .stream-tile')).toHaveCount(3)
  for (const name of names.slice(0, 3)) await expectVideoFlowing(d, `Tela de ${name}`)
  await d.page.screenshot({ path: 'ui-workspace-grid.png' })
  await share(d, '720p', '30')
  await expect(a.page.locator('.stream-grid .stream-tile')).toHaveCount(3)
  await expect(b.page.locator('.stream-grid .stream-tile')).toHaveCount(3)
  await expectVideoFlowing(a, `Tela de ${names[3]}`)
  await d.page.getByRole('button', { name: /Parar transmissão/ }).last().click()
  const shareSid = () => a.page.evaluate(async () => {
    const response = await fetch('/api/v1/servers')
    const servers = await response.json() as { id: string }[]
    const presence = await (await fetch(`/api/v1/servers/${servers[0]!.id}/presence`)).json() as { participants: { identity: string }[] }[]
    return presence.flatMap((p) => p.participants).map((p) => p.identity).sort().join(',')
  })
  const before = await shareSid()
  const captureId = await a.page.evaluate(() => (window as unknown as { __captures: MediaStream[] }).__captures[0]!.getVideoTracks()[0]!.id)
  await d.page.getByLabel(`Tela de ${names[0]}`).click()
  await expect(d.page.locator('.focus-main')).toBeVisible()
  await d.page.getByRole('button', { name: /Voltar para grade/ }).click()
  await d.page.getByRole('button', { name: `Tela cheia de ${names[0]}` }).click()
  await expect.poll(() => d.page.evaluate(() => !!document.fullscreenElement)).toBe(true)
  await d.page.keyboard.press('Escape')
  // Chromium headless nem sempre encaminha Escape ao fullscreen nativo; clique também deve sair.
  // Em tela cheia as barras só aparecem com o mouse em movimento (como uma pessoa faria antes de clicar).
  if (await d.page.evaluate(() => !!document.fullscreenElement)) {
    await d.page.mouse.move(200, 200); await d.page.mouse.move(240, 230)
    await d.page.getByRole('button', { name: `Tela cheia de ${names[0]}` }).click()
  }
  // quem transmite vê quantos estão assistindo; quem deixa de assistir sai da contagem
  const watchersOfB = b.page.getByLabel(`Transmissão de ${names[1]}`).getByRole('button', { name: /assistindo/ })
  await expect(watchersOfB).toHaveAccessibleName('3 pessoas assistindo')
  await d.page.getByRole('button', { name: `Ocultar ${names[1]}` }).click()
  await expect(d.page.locator('.stream-grid .stream-tile')).toHaveCount(2)
  await expect(watchersOfB).toHaveAccessibleName('2 pessoas assistindo')
  await watchersOfB.click()
  await expect(b.page.getByRole('dialog', { name: 'Quem está assistindo' })).toContainText(names[0]!)
  await expect(b.page.getByRole('dialog', { name: 'Quem está assistindo' })).not.toContainText(names[3]!)
  await watchersOfB.click()
  await expect.poll(() => d.page.evaluate(() => [...document.querySelectorAll('video')].filter((v) => v.getAttribute('aria-label')?.includes('B_')).length)).toBe(0)
  await a.page.locator('.primary-controls').getByRole('button', { name: 'Qualidade', exact: true }).click()
  await a.page.getByRole('dialog').getByLabel('Resolução').selectOption('720p')
  await a.page.getByRole('dialog').getByLabel('FPS', { exact: true }).selectOption('30')
  await a.page.getByRole('button', { name: 'Aplicar qualidade' }).click()
  await expect(a.page.getByRole('dialog')).toHaveCount(0)
  expect(await shareSid()).toBe(before)
  expect(await a.page.evaluate(() => (window as unknown as { __captures: MediaStream[] }).__captures[0]!.getVideoTracks()[0]!.id)).toBe(captureId)
  await expectVideoFlowing(d, `Tela de ${names[0]}`)
  await expect(a.page.locator('.preview-footer')).toContainText('30 FPS')
  await a.page.getByRole('button', { name: 'Trocar tela/janela' }).click()
  await expect.poll(() => a.page.evaluate(() => (window as unknown as { __captures: MediaStream[] }).__captures.length)).toBe(2)
  await expectVideoFlowing(d, `Tela de ${names[0]}`)
  expect(await a.page.evaluate(() => (window as unknown as { __captures: MediaStream[] }).__captures[0]!.getVideoTracks()[0]!.readyState)).toBe('ended')
  await c.page.getByRole('button', { name: /Parar transmissão/ }).last().click()
  await expect(d.page.locator('.stream-grid .stream-tile')).toHaveCount(1)
  await b.page.getByRole('button', { name: 'Sair do canal' }).click()
  await expect(d.page.locator('.compact-participant')).toHaveCount(3)
  await d.page.getByRole('button', { name: 'Não assistir' }).click()
  await expect(d.page.locator('.stream-tile')).toHaveCount(0)
  await d.page.waitForTimeout(1000)
  await d.page.getByRole('button', { name: 'Ver todas' }).click()
  await expectVideoFlowing(d, `Tela de ${names[0]}`)
  // Alternância rápida não pode deixar o player anexado à track antiga.
  await d.page.getByRole('button', { name: 'Não assistir' }).click()
  await d.page.getByRole('button', { name: 'Ver todas' }).click()
  await expectVideoFlowing(d, `Tela de ${names[0]}`)
  await d.page.setViewportSize({ width: 390, height: 844 })
  await d.page.screenshot({ path: 'ui-workspace-mobile.png' })
  expect(await d.page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  // Refresh preserva conta/servidor, mas não recaptura tela sem consentimento.
  await d.page.reload()
  await expect(d.page.locator('.user-panel')).toContainText(names[3]!)
  await expect(d.page.getByRole('button', { name: 'Servidor Amigos' })).toBeVisible()
  await d.page.getByRole('button', { name: 'Mostrar canais' }).click()
  await expect(d.page.getByRole('button', { name: 'Sair do canal' })).toBeVisible()
  await expectVideoFlowing(d, `Tela de ${names[0]}`)
  await a.page.getByRole('button', { name: /Parar transmissão/ }).last().click()
  await a.page.goto(serverUrl)
  await expect(a.page.getByRole('button', { name: /#\s*Jogos/ })).toBeVisible()
})
