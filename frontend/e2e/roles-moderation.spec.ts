async function call(p: Person, path: string, method = 'GET', data?: unknown) {
  const headers: Record<string,string> = {}
  if (method !== 'GET') headers['X-CSRF-Token'] = (await (await p.context.request.get('/api/v1/auth/csrf')).json()).token
  const response = await p.context.request.fetch(`/api/v1${path}`, { method, data, headers })
  expect(response.ok(), `${method} ${path}: ${await response.text()}`).toBe(true)
  return response.status() === 204 ? undefined : response.json()
}
